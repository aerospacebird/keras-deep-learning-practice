# -------------------- Haar Cascade 로더 (Colab/headless 호환) --------------------
def load_face_cascade():
    """여러 경로를 시도하여 Haar Cascade를 로드. 실패 혹은 cv2 바인딩 부재 시 None 반환."""
    if not hasattr(cv2, 'CascadeClassifier'):
        return None

    candidates = []

    # 1. cv2.data 경로 (일반 opencv-python)
    try:
        if hasattr(cv2, 'data') and hasattr(cv2.data, 'haarcascades'):
            candidates.append(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')
    except Exception:
        pass

    # 2. glob으로 시스템 전체 검색
    search_patterns = [
        '/usr/local/lib/python*/dist-packages/cv2/data/haarcascade_frontalface_default.xml',
        '/usr/lib/python*/dist-packages/cv2/data/haarcascade_frontalface_default.xml',
        '/usr/share/opencv*/haarcascades/haarcascade_frontalface_default.xml',
        '/usr/local/share/opencv*/haarcascades/haarcascade_frontalface_default.xml',
        'haarcascade_frontalface_default.xml',
    ]
    for pattern in search_patterns:
        candidates.extend(glob.glob(pattern))

    for path in candidates:
        if path and os.path.exists(path):
            try:
                cascade = cv2.CascadeClassifier(path)
                if cascade is not None and not cascade.empty():
                    return cascade
            except Exception:
                pass
    return None


# -------------------- 커스텀 Dataset --------------------
class TeamFaceDataset(Dataset):
    def __init__(self, root_dir, class_names, transforms=None):
        self.root_dir = Path(root_dir)
        self.class_names = class_names
        self.transforms = transforms
        self.samples = []
        self.face_cascade = load_face_cascade()  # 한 번만 로드

        for idx, name in enumerate(class_names):
            person_dir = self.root_dir / name
            if not person_dir.exists():
                continue
            for img_path in person_dir.glob("*"):
                if img_path.suffix.lower() in ['.jpg', '.jpeg', '.png']:
                    self.samples.append((str(img_path), idx + 1))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        img_path, label = self.samples[idx]
        image = cv2.imread(img_path)
        if image is None:
            image = np.zeros((224, 224, 3), dtype=np.uint8)
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
        h, w = image.shape[:2]

        faces = []
        if self.face_cascade is not None:
            try:
                gray = cv2.cvtColor(image, cv2.COLOR_RGB2GRAY)
                faces = self.face_cascade.detectMultiScale(gray, 1.1, 4, minSize=(30, 30))
            except Exception:
                faces = []

        boxes = []
        masks = []
        labels_list = []

        if faces is None or len(faces) == 0:
            # 얼굴 미검출 시 중앙 영역 사용
            cx, cy = w // 2, h // 2
            bw, bh = int(w * 0.4), int(h * 0.5)
            x1 = max(0, cx - bw // 2)
            y1 = max(0, cy - bh // 2)
            x2 = min(w, cx + bw // 2)
            y2 = min(h, cy + bh // 2)
            faces = [(x1, y1, x2 - x1, y2 - y1)]

        for (x, y, fw, fh) in faces:
            x1, y1, x2, y2 = int(x), int(y), int(x + fw), int(y + fh)
            boxes.append([x1, y1, x2, y2])
            labels_list.append(label)

            # 타원 마스크 생성
            mask = np.zeros((h, w), dtype=np.uint8)
            center = (int((x1 + x2) / 2), int((y1 + y2) / 2))
            axes = (max(1, int(fw * 0.55)), max(1, int(fh * 0.65)))
            cv2.ellipse(mask, center, axes, 0, 0, 360, 1, -1)
            masks.append(mask)

        boxes = torch.as_tensor(boxes, dtype=torch.float32)
        labels_t = torch.as_tensor(labels_list, dtype=torch.int64)
        masks_t = torch.as_tensor(np.stack(masks), dtype=torch.uint8)
        image_id = torch.tensor([idx])
        area = (boxes[:, 3] - boxes[:, 1]) * (boxes[:, 2] - boxes[:, 0])
        iscrowd = torch.zeros((len(boxes),), dtype=torch.int64)

        target = {
            "boxes": boxes,
            "labels": labels_t,
            "masks": masks_t,
            "image_id": image_id,
            "area": area,
            "iscrowd": iscrowd
        }

        if self.transforms:
            try:
                transformed = self.transforms(
                    image=image,
                    masks=masks_t.numpy(),
                    bboxes=boxes.numpy(),
                    class_labels=labels_t.numpy()
                )
                image = transformed["image"]
                target["masks"] = torch.as_tensor(transformed["masks"], dtype=torch.uint8)
                if len(transformed["bboxes"]) > 0:
                    target["boxes"] = torch.as_tensor(transformed["bboxes"], dtype=torch.float32)
                    target["labels"] = torch.as_tensor(transformed["class_labels"], dtype=torch.int64)
                else:
                    target["boxes"] = torch.zeros((0, 4), dtype=torch.float32)
                    target["labels"] = torch.zeros((0,), dtype=torch.int64)
                    target["masks"] = torch.zeros((0, h, w), dtype=torch.uint8)
            except Exception:
                image = T.ToTensor()(image)
        else:
            image = T.ToTensor()(image)

        return image, target


def get_transform(train=True):
    if train:
        return A.Compose([
            A.HorizontalFlip(p=0.5),
            A.RandomBrightnessContrast(p=0.3),
            A.HueSaturationValue(p=0.2),
            A.GaussNoise(p=0.2),
            A.Rotate(limit=15, p=0.3),
            A.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
            ToTensorV2()
        ], bbox_params=A.BboxParams(format='pascal_voc', label_fields=['class_labels'], min_visibility=0.3))
    else:
        return A.Compose([
            A.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
            ToTensorV2()
        ])


def get_model(num_classes):
    weights = MaskRCNN_ResNet50_FPN_V2_Weights.DEFAULT
    model = maskrcnn_resnet50_fpn_v2(weights=weights)

    in_features = model.roi_heads.box_predictor.cls_score.in_features
    model.roi_heads.box_predictor = FastRCNNPredictor(in_features, num_classes)

    in_features_mask = model.roi_heads.mask_predictor.conv5_mask.in_channels
    hidden_layer = 256
    model.roi_heads.mask_predictor = MaskRCNNPredictor(in_features_mask, hidden_layer, num_classes)

    return model


def collate_fn(batch):
    return tuple(zip(*batch))


