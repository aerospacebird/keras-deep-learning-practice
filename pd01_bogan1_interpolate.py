import pandas as pd
import numpy as np
print(pd.__version__)



#xit()

data = [
    '11/11/2026', '12/11/2026', '13/11/2026',
    '14/11/2026', '15/11/2026', '16/11/2026',
    '17/11/2026', '18/11/2026', '19/11/2026',
]

dates = pd.to_datetime(data, dayfirst=True)
print(dates)



print("===============================================================================")
ts = pd.Series([0, 2, np.nan, np.nan, 8, 10, np.nan, 14, np.nan], index=dates)
print(ts)

print("===============================================================================")
ts = ts.interpolate()
print(ts)

