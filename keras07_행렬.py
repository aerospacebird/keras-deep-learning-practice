# 행렬 곱셈(Matrix Multiplication)

# 행렬 곱셈은 AI·딥러닝의 핵심 연산입니다. 특히 우리가 이전에 설계했던 NPU의 MAC → PE → Systolic Array → Tensor Core 구조가 결국 대규모 행렬 곱셈을 빠르게 처리하기 위한 것입니다.

# 1. 기본 개념

# 두 행렬

# $$ A_{m\times k} $$

# 와

# $$ B_{k\times n} $$

# 을 곱하면 결과는

# $$ C_{m\times n}=A\times B $$

# 가 됩니다.

# 중요한 조건은:

# A의 열(column) 개수 = B의 행(row) 개수

# 입니다.

# 예를 들어,

# $$ A= \begin{bmatrix} 1&2&3\\ 4&5&6 \end{bmatrix} $$

# 는 \(2\times3\) 행렬이고,

# $$ B= \begin{bmatrix} 7&8\\ 9&10\\ 11&12 \end{bmatrix} $$

# 는 \(3\times2\) 행렬입니다.

# 따라서

# $$ (2\times3)(3\times2) $$

# 가 가능하고 결과는

# $$ C_{2\times2} $$

# 가 됩니다.

# 2. 실제 계산

# 첫 번째 행 × 첫 번째 열:

# $$ C_{11}=1(7)+2(9)+3(11) $$ $$ =7+18+33=58 $$

# 첫 번째 행 × 두 번째 열:

# $$ C_{12}=1(8)+2(10)+3(12) $$ $$ =8+20+36=64 $$

# 두 번째 행 × 첫 번째 열:

# $$ C_{21}=4(7)+5(9)+6(11) $$ $$ =28+45+66=139 $$

# 두 번째 행 × 두 번째 열:

# $$ C_{22}=4(8)+5(10)+6(12) $$ $$ =32+50+72=154 $$

# 따라서

# $$ \boxed{ C= \begin{bmatrix} 58&64\\ 139&154 \end{bmatrix} } $$

# 입니다.

# 3. 핵심은 MAC

# 행렬 곱셈의 한 원소는 사실상 **Multiply-Accumulate(MAC)**입니다.

# $$ C_{ij}=\sum_{k=1}^{K} A_{ik}B_{kj} $$

# 즉,

# 곱셈 → 덧셈 → 곱셈 → 덧셈 → ...

# 을 반복합니다.

# 예를 들어:

# A row:    1   2   3
#           ×   ×   ×
# B col:    7   9  11
#           ↓   ↓   ↓

#         1×7 + 2×9 + 3×11
#                  ↓
#                 58

# 이 때문에 NPU의 가장 기본적인 연산 블록이 MAC Unit입니다.
