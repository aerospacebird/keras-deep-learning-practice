# # (6, 4, 2)

# y.shape
# # (6, 2)
# ```

# 입니다.

# ### 핵심 공식

# 이 코드는 사실 다음 한 줄의 개념입니다.

# ```text
# 과거 size개 timestep  →  다음 1개 timestep 예측
# ```

# 즉,

# ```text
# X[i] = a[i : i + size]

# y[i] = a[i + size]
# ```

# 그리고 샘플의 개수는:

# ```text
# 전체 timestep - window size
# ```

# 이므로,

# ```text
# 10 - 4 = 6 samples
# ```

# 입니다.

# 따라서 RNN 입력의 3차원 구조는:

# ```text
# X.shape
# =
# (samples, timesteps, features)

# =
# (6, 4, 2)
# ```

# 가 됩니다.

# 특히 **`size`는 timestep의 길이를 결정하고, `a.shape[1]`은 feature의 개수를 결정합니다.**
# 따라서 `size=3`이면 `(7, 3, 2)`, `size=4`이면 `(6, 4, 2)`가 됩니다.
