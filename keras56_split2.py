###################################################################################
#```python
# ============================================================
# X와 y를 저장할 빈 리스트 생성
# ============================================================

# X : RNN에 입력으로 넣을 과거 데이터 묶음(window)을 저장
# y : X 바로 다음 timestep의 정답 데이터를 저장

x = []
y = []


# ============================================================
# 시계열 데이터를 size 크기의 window로 잘라서
# X와 y를 만드는 반복문
# ============================================================

# len(a)        : 전체 데이터의 timestep 개수
# size          : 한 번에 RNN에 입력할 timestep 개수
#
# 예를 들어
# len(a) = 10
# size   = 4
#
# range(len(a) - size)
# = range(10 - 4)
# = range(6)
#
# 따라서 i는
# 0, 1, 2, 3, 4, 5
# 총 6번 반복한다.
#
# 각각의 i에 대해서
# "과거 4개 timestep → 바로 다음 1개 timestep"
# 형태의 학습 데이터를 만든다.

for i in range(len(a) - size):

    # ========================================================
    # X 생성
    # ========================================================

    # 현재 i 위치부터 size개 timestep을 잘라서
    # RNN의 입력 데이터 X로 사용한다.
    #
    # a[i:i + size]
    #
    # 의미:
    # 시작 위치 = i
    # 끝 위치   = i + size
    #
    # Python slicing에서는 끝 위치는 포함하지 않는다.
    #
    # 예:
    # i = 0, size = 4
    #
    # a[0:4]
    #
    # → 0, 1, 2, 3번째 데이터를 가져온다.
    # → 총 4개의 timestep
    #
    # 즉,
    #
    # [현재 timestep부터]
    # [size개 timestep]을
    # 하나의 입력 window로 만든다.

    x.append(
        a[i:i + size]
    )


    # ========================================================
    # y 생성
    # ========================================================

    # X에 사용한 입력 window 바로 다음 timestep을
    # 정답 y로 사용한다.
    #
    # a[i + size]
    #
    # 예:
    #
    # i = 0
    # size = 4
    #
    # X = a[0:4]
    #   = 0, 1, 2, 3번째 데이터
    #
    # y = a[4]
    #   = X 바로 다음 데이터
    #
    # 즉,
    #
    # X : 과거 4개 timestep
    # y : 그 다음 1개 timestep
    #
    # RNN에게
    #
    # "과거 4개의 데이터를 보고
    #  다음 데이터를 예측하라"
    #
    # 라고 학습시키는 구조이다.

    y.append(
        a[i + size]
    )


# ============================================================
# Python list → NumPy array 변환
# ============================================================

# 지금까지 x와 y는 Python list이다.
#
# RNN/Keras 모델에 입력하기 편하도록
# NumPy 배열로 변환한다.

x = np.array(x)
y = np.array(y)


# ============================================================
# 최종적인 데이터 구조
# ============================================================

# size = 4이고
# 원본 데이터 a의 shape이 (10, 2)라면
#
# x.shape
# → (6, 4, 2)
#
# 의미:
#
# 6  = 학습 샘플 개수
# 4  = timestep 개수
# 2  = feature 개수
#
#
# y.shape
# → (6, 2)
#
# 의미:
#
# 6 = 학습 샘플 개수
# 2 = 예측할 feature 개수
# ```

# ### 실제 데이터로 확인

# 원본 `a`가 다음과 같다고 하면:

# ```python
# a = np.array([
#     [1, 9],
#     [2, 8],
